export function normalizeCity(value: string | undefined): string | undefined {
	if (!value) return undefined;
	const trimmed = value.trim();
	if (!trimmed || CITY_NOT_A_PLACE.has(trimmed)) return undefined;
	return CITY_ALIASES[trimmed] ?? trimmed;
}

export function normalizeForeignRegion(
	country: string | undefined,
	region: string | undefined,
): string | undefined {
	if (!region) return undefined;
	const trimmed = region.trim();
	if (!trimmed) return undefined;
	return FOREIGN_REGION_ALIASES[`${country ?? ""}|${trimmed}`] ?? trimmed;
}
