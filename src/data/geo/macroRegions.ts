/**
 * Корзина верхнего уровня для страны. Неизвестная страна попадает в «Азия»
 * только если это явно прописано — иначе возвращается `undefined`, и схема
 * коллекции обязана поймать это до сборки.
 */
export function getMacroRegion(country: string | undefined): MacroRegion | undefined {
	if (!country) return undefined;
	return MACRO_REGION_BY_COUNTRY[country];
}
