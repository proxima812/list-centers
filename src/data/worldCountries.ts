export const worldCountriesByLocale = {
	ru: worldCountriesRu,
	en: worldCountriesEn,
	tt: worldCountriesTt,
	qt: worldCountriesQt,
	uk: worldCountriesUk,
	de: worldCountriesDe,
	es: worldCountriesEs,
	ky: worldCountriesKy,
	uz: worldCountriesUz,
	kk: worldCountriesKk,
} satisfies Record<AppLocale, string[]>;

// Списки сопоставляются по индексу, и рассинхрон длин уже однажды раздавал
// чужие переводы (см. комментарий про «Швецию» выше). Падаем на сборке сразу.
for (const [locale, values] of Object.entries(worldCountriesByLocale)) {
	if (values.length !== worldCountriesRu.length) {
		throw new Error(
			`worldCountries: список «${locale}» (${values.length}) рассинхронизирован ` +
				`с русским (${worldCountriesRu.length}) — переводы съедут по индексу.`,
		);
	}
}

type CountryLabels = Record<AppLocale, string>;

export const countryLabelsByRu = Object.fromEntries(
	worldCountriesRu.map((country, index) => [
		country,
		Object.fromEntries(
			Object.entries(worldCountriesByLocale).map(([locale, values]) => [locale, values[index] ?? country]),
		),
	]),
) as Record<string, CountryLabels>;

export function getCountryLabels(country: string): CountryLabels {
	return (
		countryLabelsByRu[country] ?? {
			ru: country,
			en: country,
			tt: country,
			qt: country,
			uk: country,
			de: country,
			es: country,
			ky: country,
			uz: country,
			kk: country,
		}
	);
}

export function getCountryLabel(country: string, locale: AppLocale): string {
	return getCountryLabels(country)[locale] ?? country;
}
