const normalizeCity = (value?: string) =>
	value
		?.toLowerCase()
		.replaceAll("ё", "е")
		.replace(/^г\.\s*/, "")
		.replace(/^город\s+/, "")
		.replace(/^города\s+/, "")
		.replace(/^село\s+/, "")
		.trim();

export const getMapCityCoordinates = (
	city?: string,
	region?: string,
): MapCityCoordinates | undefined => {
	const candidates = [city, region].map(normalizeCity).filter(Boolean) as string[];

	for (const candidate of candidates) {
		if (cityCoordinates[candidate]) return cityCoordinates[candidate];
		for (const [matcher, key] of cityAliases) {
			if (matcher.test(candidate)) return cityCoordinates[key];
		}
	}

	return undefined;
};

export const getMapCountryCoordinates = (country?: string): MapCityCoordinates | undefined => {
	const normalizedCountry = normalizeCity(country);
	return normalizedCountry ? countryCoordinates[normalizedCountry] : undefined;
};
